//! Build-time reverse index: (numeric tag ID, family) -> tag name.
//!
//! `oxidex::tag_db::lookup_tag_name` used to answer this from a
//! `HashMap<(u16, FormatFamily), String>` built on first use, which decoded all
//! six tag databases and allocated one `String` per entry in *every* process --
//! 8.7% of a single-file `oxidex -j -a -G1` run. The answer is a pure function
//! of the YAML each tag crate already compiles in, so each crate's `build.rs`
//! now computes its share here and emits it as a sorted `static` slice.
//!
//! The rules are the ones the runtime index applied, unchanged:
//!
//! * `::Composite` tables are skipped (derived values, not tag definitions);
//! * only tables whose name starts with one of the [`IdFamily`] prefixes count;
//! * the ID is `0x`-prefixed hex or decimal, and must fit a `u16`;
//! * a name starting with a lowercase ASCII letter is an XMP namespace prefix,
//!   not a tag, unless it starts `undef` or `n/a`;
//! * the **first** occurrence of an (ID, family) pair wins, in table order and
//!   then tag order within a crate, and in crate order (core, camera, media,
//!   image, document, specialty) across crates.
//!
//! The first three rules are applied here; the cross-crate order is the
//! caller's, which consults the crates' slices in that order and takes the
//! first hit. `oxidex`'s `tag_db` tests keep the old runtime builder verbatim
//! and assert the two agree on every key.

use crate::TagDatabase;
use std::collections::HashSet;
use std::fmt::Write as _;

/// The numeric-ID families the reverse index is keyed by.
///
/// Mirrors the `FormatFamily` values the runtime index could produce; the
/// discriminant order is the sort order of the emitted slices.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum IdFamily {
    Exif,
    Gps,
    Xmp,
    Iptc,
    IccProfile,
    Photoshop,
}

impl IdFamily {
    /// The family a table contributes to, from its name's module prefix.
    #[must_use]
    pub fn of_table(table_name: &str) -> Option<Self> {
        [
            ("Exif::", Self::Exif),
            ("GPS::", Self::Gps),
            ("XMP::", Self::Xmp),
            ("IPTC::", Self::Iptc),
            ("ICC_Profile::", Self::IccProfile),
            ("Photoshop::", Self::Photoshop),
        ]
        .into_iter()
        .find_map(|(prefix, family)| table_name.starts_with(prefix).then_some(family))
    }

    fn path(self) -> &'static str {
        match self {
            Self::Exif => "oxidex_tags_shared::IdFamily::Exif",
            Self::Gps => "oxidex_tags_shared::IdFamily::Gps",
            Self::Xmp => "oxidex_tags_shared::IdFamily::Xmp",
            Self::Iptc => "oxidex_tags_shared::IdFamily::Iptc",
            Self::IccProfile => "oxidex_tags_shared::IdFamily::IccProfile",
            Self::Photoshop => "oxidex_tags_shared::IdFamily::Photoshop",
        }
    }
}

/// One emitted row: (family, numeric tag ID, bare tag name).
pub type ReverseEntry = (IdFamily, u16, &'static str);

fn parse_tag_id(id: &str) -> Option<u16> {
    match id.strip_prefix("0x") {
        Some(hex) => u16::from_str_radix(hex, 16).ok(),
        None => id.parse::<u16>().ok(),
    }
}

fn is_valid_tag_name(name: &str) -> bool {
    let Some(first) = name.chars().next() else {
        return false;
    };
    !first.is_ascii_lowercase() || name.starts_with("undef") || name.starts_with("n/a")
}

/// This database's reverse-index rows: first occurrence per (family, ID) in
/// table-then-tag order, sorted by (family, ID) for binary search.
#[must_use]
pub fn reverse_entries(db: &TagDatabase) -> Vec<(IdFamily, u16, String)> {
    let mut seen = HashSet::new();
    let mut rows = Vec::new();
    for table in &db.tables {
        if table.name.contains("::Composite") {
            continue;
        }
        let Some(family) = IdFamily::of_table(&table.name) else {
            continue;
        };
        for tag in &table.tags {
            let Some(id) = parse_tag_id(&tag.id) else {
                continue;
            };
            if is_valid_tag_name(&tag.name) && seen.insert((family, id)) {
                rows.push((family, id, tag.name.clone()));
            }
        }
    }
    rows.sort_by_key(|(family, id, _)| (*family, *id));
    rows
}

/// Rust source defining `pub static TAG_ID_REVERSE: &[ReverseEntry]`.
#[must_use]
pub fn render_reverse_index(rows: &[(IdFamily, u16, String)]) -> String {
    let mut out = String::with_capacity(rows.len() * 48 + 256);
    out.push_str(
        "// Generated by build.rs from this crate's tag YAML. DO NOT EDIT.\n\
         // Paths are fully qualified: a crate with no numeric-ID tables emits an\n\
         // empty slice, and a `use` would then be an unused import.\n\
         /// (family, numeric tag ID) -> tag name, sorted for binary search.\n\
         pub static TAG_ID_REVERSE: &[oxidex_tags_shared::ReverseEntry] = &[\n",
    );
    for (family, id, name) in rows {
        let _ = writeln!(out, "    ({}, 0x{id:04X}, {name:?}),", family.path());
    }
    out.push_str("];\n");
    out
}

/// Binary-search one crate's emitted slice.
#[must_use]
pub fn lookup_reverse(rows: &[ReverseEntry], family: IdFamily, id: u16) -> Option<&'static str> {
    rows.binary_search_by_key(&(family, id), |(f, i, _)| (*f, *i))
        .ok()
        .map(|index| rows[index].2)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{Tag, TagTable};

    fn tag(id: &str, name: &str) -> Tag {
        Tag {
            id: id.to_string(),
            name: name.to_string(),
            writable: false,
            type_name: None,
            description: None,
        }
    }

    #[test]
    fn first_occurrence_wins_and_filters_apply() {
        let db = TagDatabase {
            tables: vec![
                TagTable {
                    name: "Exif::Composite".into(),
                    tags: vec![tag("0x0001", "Derived")],
                },
                TagTable {
                    name: "Canon::Main".into(),
                    tags: vec![tag("0x0001", "NotAFamily")],
                },
                TagTable {
                    name: "Exif::Main".into(),
                    tags: vec![
                        tag("0x0002", "x"),
                        tag("0x0002", "Second"),
                        tag("0x0002", "Third"),
                        tag("7", "Decimal"),
                        tag("0x1FFFF", "TooWide"),
                        tag("Name", "NotNumeric"),
                    ],
                },
                TagTable {
                    name: "GPS::Main".into(),
                    tags: vec![tag("0x0002", "GpsTwo")],
                },
            ],
        };
        let rows = reverse_entries(&db);
        assert_eq!(
            rows,
            vec![
                (IdFamily::Exif, 2, "Second".to_string()),
                (IdFamily::Exif, 7, "Decimal".to_string()),
                (IdFamily::Gps, 2, "GpsTwo".to_string()),
            ]
        );
        let src = render_reverse_index(&rows);
        assert!(src.contains("(oxidex_tags_shared::IdFamily::Exif, 0x0002, \"Second\"),"));
        assert!(!src.contains("\nuse "), "generated source must not import");
    }
}
