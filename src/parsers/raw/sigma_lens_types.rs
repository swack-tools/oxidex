/// Looks up a Sigma `LensType` id.
pub fn lookup(lens_type: u32) -> Option<&'static str> {
    SIGMA_LENS_TYPES
        .binary_search_by_key(&lens_type, |(id, _)| *id)
        .ok()
        .map(|index| SIGMA_LENS_TYPES[index].1)
}
