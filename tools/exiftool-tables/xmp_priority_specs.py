"""Generate the per-tag FoundTag priorities ExifTool's XMP read path uses.

Input is capture_xmp_priorities.pl's JSON for the pinned tree (committed as
fixtures/xmp_priorities_13_59.json). Output is
src/parsers/xmp/generated_priorities.rs: for every key of
%Image::ExifTool::XMP::Main that names a tag table (the namespace prefix after
%stdXlatNS, which is what FoundXMP looks the table up by), each tag Name --
including the flattened structure tags AddFlattenedTags generates -- with its
effective FoundTag priority: the tag's Priority, else the table's PRIORITY,
else 0 when the tag is Avoid, else 1.

A property that is not an entry of its namespace's table, or whose prefix
names no table, is minted by FoundXMP with `Priority => 0`; the generated
lookup reports it as absent and the reader treats absent as 0.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tools/exiftool-tables/fixtures/xmp_priorities_13_59.json"
RUST = ROOT / "src/parsers/xmp/generated_priorities.rs"
SCHEMA_KEYS = {"exiftool_version", "namespaces"}
NAMESPACE_KEYS = {"table", "table_priority", "tags"}
PRINTABLE = re.compile(r"[\x20-\x7e]+")


TESTS = """#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_for_binary_search() {
        assert!(XMP_TAG_PRIORITIES.windows(2).all(|pair| pair[0].0 < pair[1].0));
        for (_, tags) in XMP_TAG_PRIORITIES {
            assert!(tags.windows(2).all(|pair| pair[0].0 < pair[1].0));
        }
    }

    #[test]
    fn effective_priorities_follow_found_tag() {
        // Table PRIORITY => 0 (XMP.pm %Image::ExifTool::XMP::tiff).
        assert_eq!(xmp_tag_priority("tiff", "NativeDigest"), Some(0));
        // Tag Priority => 0 (xmp:CreateDate) and => -1 (pdf:Keywords).
        assert_eq!(xmp_tag_priority("xmp", "CreateDate"), Some(0));
        assert_eq!(xmp_tag_priority("pdf", "Keywords"), Some(-1));
        // Plain entries default to 1; tables keyed after %stdXlatNS.
        assert_eq!(xmp_tag_priority("iptcCore", "CountryCode"), Some(1));
        assert_eq!(xmp_tag_priority("photoshop", "Headline"), Some(1));
        // Not an entry of its table, or no table: absent (FoundXMP mints 0).
        assert_eq!(xmp_tag_priority("dc", "Test"), None);
        assert_eq!(xmp_tag_priority("xxxx", "Test"), None);
    }
}
"""


def validate(capture: dict) -> None:
    if set(capture) != SCHEMA_KEYS:
        raise ValueError("XMP priority capture has unexpected keys")
    if not capture["namespaces"]:
        raise ValueError("XMP priority capture has no namespaces")
    for prefix, fact in capture["namespaces"].items():
        if set(fact) != NAMESPACE_KEYS:
            raise ValueError(f"namespace {prefix} has unexpected keys")
        if fact["table_priority"] is not None and not isinstance(fact["table_priority"], int):
            raise ValueError(f"namespace {prefix} has a non-integer table PRIORITY")
        for name, priority in fact["tags"].items():
            if not isinstance(priority, int) or isinstance(priority, bool) or not -128 <= priority <= 127:
                raise ValueError(f"{prefix}:{name} has priority {priority!r}")
        strings = [prefix, fact["table"], *fact["tags"]]
        if not all(isinstance(value, str) and PRINTABLE.fullmatch(value) and "\\" not in value and '"' not in value
                   for value in strings):
            raise ValueError("priority strings must be printable ASCII without quotes or backslashes")


def render(capture: dict) -> str:
    validate(capture)
    namespaces = capture["namespaces"]
    lines = [
        "// @generated by tools/exiftool-tables/xmp_priority_specs.py -- do not edit.",
        f"// Source: ExifTool {capture['exiftool_version']} XMP::Main tag tables (after AddFlattenedTags);",
        "// effective FoundTag priority = Priority // table PRIORITY // (Avoid ? 0 : 1).",
        "",
        "/// `(XMP::Main key, [(tag Name, effective priority)])`, both levels sorted.",
        "#[rustfmt::skip]",
        "pub static XMP_TAG_PRIORITIES: &[(&str, &[(&str, i8)])] = &[",
    ]
    for prefix in sorted(namespaces):
        lines.append(f'    ("{prefix}", &[')
        for name, priority in sorted(namespaces[prefix]["tags"].items()):
            lines.append(f'        ("{name}", {priority}),')
        lines.append("    ]),")
    lines += ["];", "",
              "/// The effective FoundTag priority of tag `name` in the XMP table ExifTool",
              "/// selects for `namespace` (the prefix after `%stdXlatNS`), or `None` when the",
              "/// table has no such entry or there is no table -- which FoundXMP mints at",
              "/// `Priority => 0`.",
              "pub fn xmp_tag_priority(namespace: &str, name: &str) -> Option<i8> {",
              "    let tags = XMP_TAG_PRIORITIES",
              "        .binary_search_by(|(known, _)| (*known).cmp(namespace))",
              "        .ok()",
              "        .map(|index| XMP_TAG_PRIORITIES[index].1)?;",
              "    tags.binary_search_by(|(known, _)| (*known).cmp(name))",
              "        .ok()",
              "        .map(|index| tags[index].1)",
              "}", ""]
    lines += TESTS.splitlines()
    return "\n".join(lines) + "\n"


def formatted(rust: str) -> str:
    """rustfmt the rendered source so the committed file passes `cargo fmt --check`."""
    import subprocess
    run = subprocess.run(["rustfmt", "--edition", "2024", "--config-path", str(ROOT / "rustfmt.toml"), "--emit", "stdout"],
                         input=rust, text=True, capture_output=True, check=True)
    return run.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--capture", type=Path, default=FIXTURE)
    parser.add_argument("--fixture-out", type=Path)
    parser.add_argument("--rust-out", type=Path, default=RUST)
    args = parser.parse_args()
    capture = json.loads(args.capture.read_text())
    rust = render(capture)
    if args.fixture_out:
        args.fixture_out.write_text(json.dumps(capture, sort_keys=True, indent=1, ensure_ascii=False) + "\n")
    args.rust_out.write_text(formatted(rust))
    tags = sum(len(fact["tags"]) for fact in capture["namespaces"].values())
    print(f"{len(capture['namespaces'])} XMP namespace tables, {tags} tag priorities")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
