#!/usr/bin/env python3
"""Render the exact runtime Font.pm %ttLang lookup as a Rust source artifact."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
PIN = (ROOT / ".exiftool-version").read_text(encoding="utf-8").strip()
FIXTURE = ROOT / "tools/exiftool-tables/fixtures/font_languages.json"
RUST = ROOT / "src/parsers/font/generated_languages.rs"
PLATFORMS = ("Custom", "ISO", "Macintosh", "Unicode", "Windows")
PLATFORM_IDS = {"Unicode": 0, "Macintosh": 1, "ISO": 2, "Windows": 3, "Custom": 4}
SHA256 = re.compile(r"[0-9a-f]{64}\Z")
LANGUAGE = re.compile(r"[A-Za-z0-9-]+\Z")
PINNED_SHA = "445331268b67afc3c3900917f9fd678c3cf7ecc515892128783543cd2d7c9f46"


def validate(capture: dict) -> None:
    if not isinstance(capture, dict) or set(capture) != {"exiftool_version", "source_sha256", "platforms"}:
        raise ValueError("Font language capture has unexpected keys")
    if capture["exiftool_version"] != PIN:
        raise ValueError("Font language capture does not match the repository pin")
    if not isinstance(capture["source_sha256"], str) or not SHA256.fullmatch(capture["source_sha256"]):
        raise ValueError("Font.pm source digest is invalid")
    if PIN == "13.59" and capture["source_sha256"] != PINNED_SHA:
        raise ValueError("Font.pm source digest does not match the pinned source")
    platforms = capture["platforms"]
    if not isinstance(platforms, dict) or set(platforms) != set(PLATFORMS):
        raise ValueError("Font language platforms differ from the expected five")
    for platform in PLATFORMS:
        values = platforms[platform]
        if not isinstance(values, dict):
            raise ValueError(f"{platform} is not a map")
        for key, value in values.items():
            if not isinstance(key, str) or not re.fullmatch(r"(?:0|[1-9][0-9]*)", key) or int(key) > 65535:
                raise ValueError(f"invalid {platform} language ID {key!r}")
            if not isinstance(value, str) or not value or not LANGUAGE.fullmatch(value):
                raise ValueError(f"invalid {platform}/{key} language {value!r}")
    if PIN == "13.59":
        expected_counts = (0, 0, 117, 0, 210)
        if tuple(len(platforms[name]) for name in PLATFORMS) != expected_counts:
            raise ValueError("pinned Font language count differs from loaded %ttLang")
        if (platforms["Windows"].get("1044") != "no-NO"
                or platforms["Macintosh"].get("9") != "no"
                or platforms["Macintosh"].get("0") != "en"
                or "9" in platforms["Windows"]):
            raise ValueError("pinned Font platform-separation sentinel differs")


def render(capture: dict) -> str:
    validate(capture)
    lines = [
        "// @generated by tools/exiftool-tables/font_language_specs.py -- do not edit.",
        f"// Source: ExifTool {capture['exiftool_version']} Image/ExifTool/Font.pm %ttLang.",
        f"// Source SHA256: {capture['source_sha256']}",
        "",
        "/// Runtime %ttLang lookup. Platform IDs are kept distinct; absent IDs return None.",
        "#[rustfmt::skip]",
        "pub(super) fn font_language(platform_id: u16, language_id: u16) -> Option<&'static str> {",
        "    let entries: &[(u16, &str)] = match platform_id {",
    ]
    for platform in PLATFORMS:
        values = capture["platforms"][platform]
        lines.append(f"        {PLATFORM_IDS[platform]} => &[")
        for key in sorted(values, key=int):
            lines.append(f'            ({int(key)}, "{values[key]}"),')
        lines.append("        ],")
    lines += [
        "        _ => return None,",
        "    };",
        "    entries.binary_search_by_key(&language_id, |(id, _)| *id)",
        "        .ok().map(|index| entries[index].1)",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--capture", type=Path, required=True)
    parser.add_argument("--fixture-out", type=Path, default=FIXTURE)
    parser.add_argument("--rust-out", type=Path, default=RUST)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    capture = json.loads(args.capture.read_text(encoding="utf-8"))
    rendered = render(capture)
    fixture_text = json.dumps(capture, sort_keys=True, indent=2, ensure_ascii=False) + "\n"
    for path, desired in ((args.fixture_out, fixture_text), (args.rust_out, rendered)):
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != desired:
                raise SystemExit(f"stale Font language artifact: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(desired, encoding="utf-8")


if __name__ == "__main__":
    main()
