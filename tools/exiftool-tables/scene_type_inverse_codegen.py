#!/usr/bin/env python3
"""Select Exif::Main SceneType's raw write inverse from the pinned source."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUST = ROOT / "src/cli/generated_scene_type_inverse.rs"
LEDGER = ROOT / "tools/exiftool-tables/scene_type_inverse_ledger.json"
INVERSES = {"chr($val)": "unmasked_chr", "chr($val & 0xff)": "masked_chr"}


def compile_document(document: dict) -> dict:
    pin = (ROOT / ".exiftool-version").read_text().strip()
    if document.get("exiftool_version") != pin:
        raise ValueError("SceneType inverse source differs from repository pin")
    try:
        row = document["modules"]["Exif"]["tables"]["Main"]["tags"]["41729"]
    except (KeyError, TypeError) as exc:
        raise ValueError("selected Exif::Main 0xa301 SceneType row is absent") from exc
    expected_print = {"kind": "enum", "directives": None,
                      "map": {"1": "Directly photographed"}}
    if (not isinstance(row, dict) or set(row) != {"Name", "Writable", "ValueConvInv", "PrintConv"}
            or row["Name"] != "SceneType" or row["Writable"] != "undef"
            or row["PrintConv"] != expected_print):
        raise ValueError("unreviewed Exif::Main SceneType declaration")
    inverse = row["ValueConvInv"]
    if (not isinstance(inverse, dict) or set(inverse) != {"kind", "expr"}
            or inverse["kind"] != "expr" or inverse["expr"] not in INVERSES):
        raise ValueError("unreviewed Exif::Main SceneType ValueConvInv")
    return {"schema": "scene_type_inverse_v1", "exiftool_version": pin,
            "source_table": "Exif::Main", "source_tag_id": "0xa301",
            "source_row_sha256": hashlib.sha256(json.dumps(
                row, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()).hexdigest(),
            "source_value_conv_inv": inverse["expr"], "mode": INVERSES[inverse["expr"]]}


def render_rust(result: dict) -> str:
    masked = "true" if result["mode"] == "masked_chr" else "false"
    return ("// @generated by tools/exiftool-tables/scene_type_inverse_codegen.py; DO NOT EDIT.\n"
            f"pub(crate) const SCENE_TYPE_MASKS_TO_BYTE: bool = {masked};\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dump", required=True, type=Path)
    parser.add_argument("--rust", type=Path, default=RUST)
    parser.add_argument("--ledger", type=Path, default=LEDGER)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--replace", action="store_true")
    args = parser.parse_args()
    if args.check and args.replace:
        parser.error("--check and --replace are mutually exclusive")
    result = compile_document(json.loads(args.dump.read_text()))
    for path, body in ((args.rust, render_rust(result)),
                       (args.ledger, json.dumps(result, sort_keys=True, indent=2) + "\n")):
        if args.check:
            if not path.is_file() or path.read_text() != body:
                parser.error(f"stale SceneType inverse artifact: {path}")
        elif path.exists() and not args.replace:
            parser.error(f"output exists: {path}; use --replace")
        else:
            path.write_text(body)


if __name__ == "__main__":
    main()
