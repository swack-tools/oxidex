#!/usr/bin/env python3
"""Select the absent PNG text-date shift behavior from the native writer.

The 11.78 AddChunks condition accepts IsOverwriting's -1 (unknown) for an
absent shifted tag. Later sources require a positive result. This is a narrow
protocol fact, not a release-number test.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re


class UnsupportedSource(ValueError):
    pass


def source_fact(lib: Path) -> tuple[bool, dict[str, str]]:
    paths = {
        "write_png": lib / "Image/ExifTool/WritePNG.pl",
        "writer": lib / "Image/ExifTool/Writer.pl",
        "png": lib / "Image/ExifTool/PNG.pm",
        "shortcuts": lib / "Image/ExifTool/Shortcuts.pm",
    }
    source = {name: path.read_text() for name, path in paths.items()}
    body_match = re.search(r"^sub AddChunks\([^\n]*\)\n\{(?P<body>.*?)^\}\n", source["write_png"], re.M | re.S)
    if body_match is None:
        raise UnsupportedSource("WritePNG AddChunks body unavailable")
    body = body_match.group("body")
    # Anchor the complete decision through GetNewValue. A new condition or
    # competing IsOverwriting use must be reviewed before emitting a mode.
    decision = re.search(
        r"foreach \$tag \(sort keys %\$addTags\) \{\s*"
        r"my \$tagInfo = \$\$addTags\{\$tag\};\s*"
        r"(?P<fake>next if \$\$tagInfo\{FakeTag\};[^\n]*\n\s*)?"
        r"my \$nvHash = \$et->GetNewValueHash\(\$tagInfo\);\s*"
        r"\# \(native PNG information is always preferred,[^\n]*\)\s*"
        r"next unless (?P<guard>[^;]+);\s*"
        r"my \$val = \$et->GetNewValue\(\$nvHash\);",
        body,
    )
    if decision is None or body.count("$et->IsOverwriting($nvHash)") != 1:
        raise UnsupportedSource("AddChunks absent-tag guard is unreviewed")
    guard = decision.group("guard")
    if guard == "$et->IsOverwriting($nvHash)" and decision.group("fake") is None:
        creates_literal = True
    elif guard == "$$nvHash{IsCreating} or $et->IsOverwriting($nvHash) > 0" and decision.group("fake") is not None:
        creates_literal = False
    else:
        raise UnsupportedSource("AddChunks absent-tag guard changed")
    writer = source["writer"]
    if not re.search(r"if \(\$permanent or \$shift\) \{\s*# don't create permanent or Shift-ed tag but define IsCreating\s*# so we know that it is the preferred tag\s*\$\$nvHash\{IsCreating\} = 0;", writer):
        raise UnsupportedSource("Writer shifted-tag IsCreating rule changed")
    png = source["png"]
    if not re.search(r"'create-date'\s*=>\s*\{\s*Name => 'CreateDate',\s*Groups => \{ 2 => 'Time' \},\s*Shift => 'Time',", png):
        raise UnsupportedSource("PNG create-date shift declaration changed")
    shortcuts = source["shortcuts"]
    if not re.search(r"AllDates\s*=>\s*\[\s*'DateTimeOriginal',\s*'CreateDate',\s*'ModifyDate',\s*\]", shortcuts):
        raise UnsupportedSource("AllDates shortcut changed")
    hashes = {name: hashlib.sha256(path.read_bytes()).hexdigest() for name, path in paths.items()}
    return creates_literal, hashes


def render(lib: Path) -> str:
    creates_literal, hashes = source_fact(lib)
    lines = ["// @generated by png_shift_contract.py from selected ExifTool source.\n"]
    lines += [f"// {name} SHA-256: {digest}\n" for name, digest in sorted(hashes.items())]
    lines += [f"pub(crate) const PNG_ABSENT_CREATE_DATE_SHIFT_LITERAL: bool = {str(creates_literal).lower()};\n"]
    return "".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("lib", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(render(args.lib))


if __name__ == "__main__":
    main()
