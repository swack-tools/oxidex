#!/usr/bin/env python3
"""Emit `src/writers/generated_tag_exists.rs`: every tag name the pinned
ExifTool's `SetNewValue` accepts as *defined*.

`exiftool -NoSuchTag=v file` answers ``Warning: Tag 'NoSuchTag' is not
defined`` / ``Nothing to do.`` and exits 1 (Writer.pl:580-590, exiftool:1812).
The test Writer.pl applies is `TagLookup::TagExists` (TagLookup.pm:13976):
a name is defined when it is a key of the generated `%tagLookup` (writable
candidates) or `%tagExists` (every other known name) hash. A name that fails
that test but is a `%Image::ExifTool::Shortcuts::Main` key is expanded by
SetNewValue before the check (Writer.pl:562-578), so shortcuts are defined
too.

Both TagLookup hashes are file-scoped lexicals, so their keys are read from
the generated source text between their `my %... = (` and `);` lines, and
every extracted key is then proven with the pinned interpreter: `TagExists`
must answer true for each one, and false for a control name. Shortcut keys
come from the pinned interpreter directly.

Usage:
    tag_exists_codegen.py --exiftool-dir <pinned tree> --perl <pinned perl> \
        --output src/writers/generated_tag_exists.rs
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
KEY = re.compile(r"^\t'([^']+)' => ")


def block_keys(text: str, opener: str) -> list[str]:
    start = text.index(opener)
    end = text.index("\n);\n", start)
    keys = []
    for line in text[start:end].splitlines()[1:]:
        match = KEY.match(line)
        if match is None:
            raise SystemExit(f"unrecognized {opener!r} line: {line!r}")
        keys.append(match.group(1))
    return keys


def perl(perl_bin: str, lib: Path, script: str, stdin: str = "") -> str:
    env = {k: v for k, v in os.environ.items()
           if k not in {"PERL5LIB", "PERLLIB", "PERL5OPT", "EXIFTOOL"}}
    run = subprocess.run([perl_bin, f"-I{lib}", "-e", script], input=stdin,
                         capture_output=True, text=True, env=env, check=True)
    return run.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--exiftool-dir", required=True, type=Path)
    parser.add_argument("--perl", required=True)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    pinned = (REPO / ".exiftool-version").read_text().strip()
    lib = args.exiftool_dir / "lib"
    version = perl(args.perl, lib, "use Image::ExifTool; print $Image::ExifTool::VERSION")
    if version != pinned:
        raise SystemExit(f"oracle is ExifTool {version}, pin is {pinned}")

    lookup_pm = lib / "Image/ExifTool/TagLookup.pm"
    shortcuts_pm = lib / "Image/ExifTool/Shortcuts.pm"
    text = lookup_pm.read_text(encoding="latin-1")
    writable = block_keys(text, "my %tagLookup = (")
    existing = block_keys(text, "my %tagExists = (")
    shortcuts = perl(args.perl, lib,
                     "use Image::ExifTool::Shortcuts; "
                     "print lc($_), qq(\\n) for keys %Image::ExifTool::Shortcuts::Main").split()

    names = sorted(set(writable) | set(existing) | set(shortcuts))
    # Prove every extracted TagLookup key against the interpreter's own test.
    probe = perl(args.perl, lib,
                 "use Image::ExifTool; use Image::ExifTool::TagLookup qw(TagExists); "
                 "my $bad = 0; while (<STDIN>) { chomp; $bad++ unless TagExists($_) } "
                 "print $bad; print TagExists('oxidexnosuchtagcontrol') ? ' control-defined' : ''",
                 "\n".join(sorted(set(writable) | set(existing))) + "\n")
    if probe != "0":
        raise SystemExit(f"TagExists disagrees with the extracted keys: {probe}")
    if any(name != name.lower() or not name for name in names):
        raise SystemExit("a captured name is not lower-case")

    lookup_sha = hashlib.sha256(lookup_pm.read_bytes()).hexdigest()
    shortcuts_sha = hashlib.sha256(shortcuts_pm.read_bytes()).hexdigest()
    out = [
        "// @generated by tools/exiftool-tables/tag_exists_codegen.py; do not edit.\n",
        f"// ExifTool {pinned}: TagLookup.pm %tagLookup ({len(set(writable))}) + %tagExists "
        f"({len(set(existing))}) + Shortcuts::Main ({len(set(shortcuts))}) = {len(names)} names.\n",
        "/// Provenance of [`TAG_EXISTS`].\n",
        "pub(crate) struct TagExistsCapture {\n",
        "    pub exiftool_version: &'static str,\n",
        "    pub tag_lookup_sha256: &'static str,\n",
        "    pub shortcuts_sha256: &'static str,\n",
        "}\n",
        "pub(crate) const TAG_EXISTS_CAPTURE: TagExistsCapture = TagExistsCapture {\n",
        f"    exiftool_version: \"{pinned}\",\n",
        f"    tag_lookup_sha256: \"{lookup_sha}\",\n",
        f"    shortcuts_sha256: \"{shortcuts_sha}\",\n",
        "};\n",
        "/// Lower-case names `SetNewValue` treats as defined, sorted for binary search.\n",
        "pub(crate) const TAG_EXISTS: &[&str] = &[\n",
    ]
    out.extend(f"    \"{name}\",\n" for name in names)
    out.append("];\n")
    args.output.write_text("".join(out))
    print(f"wrote {args.output}: {len(names)} names", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
