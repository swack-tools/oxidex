"""Generate the XMP namespace table ExifTool's read path uses for family-1 groups.

Input is capture_xmp_namespaces.pl's JSON for the pinned tree (committed as
fixtures/xmp_namespaces_13_59.json). Output is src/parsers/xmp/generated_namespaces.rs:

- URI_PREFIXES: the %uri2ns reverse lookup every read starts from (the
  exiftool.ca seed plus XMP.pm's static %nsURI), sorted by URI;
- TABLE_NAMESPACES: namespaces a tag table registers only once it has loaded
  (ExifTool.pm GetTagTable); a read knows them only after that table loaded;
- STD_XLAT: %stdXlatNS, applied to the resolved prefix.

ExifTool names a tag from a known namespace URI with family-1 group
`XMP-<translated prefix>`: URI -> prefix (URI_PREFIXES, or TABLE_NAMESPACES
once loaded) -> %stdXlatNS (XMP.pm FoundXMP). Unknown URIs keep their document
prefix under per-packet rules the reader implements. Structure namespaces are
registered only when writing and are not part of this table.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tools/exiftool-tables/fixtures/xmp_namespaces_13_59.json"
RUST = ROOT / "src/parsers/xmp/generated_namespaces.rs"
SCHEMA_KEYS = {"exiftool_version", "static", "tables", "std_xlat", "uri2ns_seed"}
SEED = {"http://ns.exiftool.ca/1.0/": "et"}
PRINTABLE = re.compile(r"[\x20-\x7e]+")


TESTS = """#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_for_binary_search() {
        assert!(URI_PREFIXES.windows(2).all(|pair| pair[0].0 < pair[1].0));
        assert!(TABLE_NAMESPACES.windows(2).all(|pair| pair[0].0 < pair[1].0));
        assert!(STD_XLAT.windows(2).all(|pair| pair[0].0 < pair[1].0));
    }

    #[test]
    fn exiftool_prefixes_for_known_and_unknown_uris() {
        assert_eq!(
            standard_prefix("http://purl.org/dc/elements/1.1/"),
            Some("dc")
        );
        assert_eq!(standard_prefix("http://ns.adobe.com/xap/1.0/"), Some("xmp"));
        assert_eq!(standard_prefix("adobe:ns:meta/"), Some("x"));
        assert_eq!(standard_prefix("http://example.com/unknown/"), None);
        // Registered only once its tag table loads.
        assert_eq!(
            standard_prefix("http://ns.google.com/photos/dd/1.0/device/"),
            None
        );
        assert_eq!(
            table_namespace("http://ns.google.com/photos/dd/1.0/device/"),
            Some(("Device", "Image::ExifTool::Google::Device"))
        );
    }

    #[test]
    fn group1_prefix_applies_std_xlat_after_the_uri_lookup() {
        assert_eq!(
            group1_prefix("http://iptc.org/std/Iptc4xmpCore/1.0/xmlns/"),
            Some("iptcCore")
        );
        assert_eq!(
            group1_prefix("http://purl.org/dc/elements/1.1/"),
            Some("dc")
        );
        assert_eq!(translated_prefix("dc"), "dc");
    }
}
"""


def read_lookup(capture: dict) -> dict[str, str]:
    """XMP.pm's initial %uri2ns: the seed, then every static prefix's URI."""
    return {**capture["uri2ns_seed"], **{uri: prefix for prefix, uri in capture["static"].items()}}


def validate(capture: dict) -> None:
    if set(capture) != SCHEMA_KEYS:
        raise ValueError("XMP namespace capture has unexpected keys")
    if capture["uri2ns_seed"] != SEED:
        raise ValueError("XMP namespace capture has an unexpected uri2ns seed")
    static, tables = capture["static"], capture["tables"]
    if len(set(static.values())) != len(static):
        raise ValueError("two static prefixes share a URI")
    lookup = read_lookup(capture)
    for prefix, fact in tables.items():
        if set(fact) != {"uri", "table"} or prefix in static or fact["uri"] in lookup:
            raise ValueError(f"table namespace {prefix} overlaps the static read lookup")
    if len({fact["uri"] for fact in tables.values()}) != len(tables):
        raise ValueError("two table namespaces share a URI")
    strings = [*lookup, *lookup.values(), *capture["std_xlat"], *capture["std_xlat"].values()]
    strings += [value for prefix, fact in tables.items() for value in (prefix, fact["uri"], fact["table"])]
    if not all(isinstance(value, str) and PRINTABLE.fullmatch(value) and "\\" not in value and '"' not in value
               for value in strings):
        raise ValueError("namespace strings must be printable ASCII without quotes or backslashes")


def rust_str(value: str) -> str:
    return '"' + value + '"'


def render(capture: dict) -> str:
    validate(capture)
    lines = [
        "// @generated by tools/exiftool-tables/xmp_namespace_specs.py -- do not edit.",
        f"// Source: ExifTool {capture['exiftool_version']} XMP.pm %nsURI, %uri2ns seed, %stdXlatNS;",
        "// tag-table NAMESPACE registrations (ExifTool.pm GetTagTable).",
        "",
        "/// ExifTool's initial `%uri2ns`: namespace URI -> standard prefix, sorted by URI.",
        "#[rustfmt::skip]",
        "pub static URI_PREFIXES: &[(&str, &str)] = &[",
    ]
    lines += [f"    ({rust_str(uri)}, {rust_str(prefix)})," for uri, prefix in sorted(read_lookup(capture).items())]
    lines += ["];", "",
              "/// Namespaces a tag table registers when it loads: (URI, prefix, table), sorted by URI.",
              "/// A read knows one only after its table has loaded.",
              "#[rustfmt::skip]",
              "pub static TABLE_NAMESPACES: &[(&str, &str, &str)] = &["]
    lines += [f"    ({rust_str(fact['uri'])}, {rust_str(prefix)}, {rust_str(fact['table'])}),"
              for prefix, fact in sorted(capture["tables"].items(), key=lambda item: item[1]["uri"])]
    lines += ["];", "",
              "/// ExifTool's `%stdXlatNS`: resolved prefix -> reported prefix, sorted by prefix.",
              "#[rustfmt::skip]",
              "pub static STD_XLAT: &[(&str, &str)] = &["]
    lines += [f"    ({rust_str(key)}, {rust_str(value)})," for key, value in sorted(capture["std_xlat"].items())]
    lines += ["];", "",
              "/// Standard prefix every read knows for a namespace URI.",
              "pub fn standard_prefix(uri: &str) -> Option<&'static str> {",
              "    URI_PREFIXES",
              "        .binary_search_by(|(known, _)| (*known).cmp(uri))",
              "        .ok()",
              "        .map(|index| URI_PREFIXES[index].1)",
              "}", "",
              "/// Prefix and table for a namespace known only once that tag table loads.",
              "pub fn table_namespace(uri: &str) -> Option<(&'static str, &'static str)> {",
              "    TABLE_NAMESPACES",
              "        .binary_search_by(|(known, _, _)| (*known).cmp(uri))",
              "        .ok()",
              "        .map(|index| (TABLE_NAMESPACES[index].1, TABLE_NAMESPACES[index].2))",
              "}", "",
              "/// `%stdXlatNS` applied to a resolved prefix (identity when not listed).",
              "pub fn translated_prefix(prefix: &str) -> &str {",
              "    STD_XLAT",
              "        .binary_search_by(|(known, _)| (*known).cmp(prefix))",
              "        .ok()",
              "        .map_or(prefix, |index| STD_XLAT[index].1)",
              "}", "",
              "/// Family-1 group suffix ExifTool reports for a URI every read knows:",
              "/// the standard prefix after `%stdXlatNS` (`XMP-<suffix>`).",
              "pub fn group1_prefix(uri: &str) -> Option<&'static str> {",
              "    standard_prefix(uri).map(|prefix| {",
              "        STD_XLAT",
              "            .binary_search_by(|(known, _)| (*known).cmp(prefix))",
              "            .ok()",
              "            .map_or(prefix, |index| STD_XLAT[index].1)",
              "    })",
              "}", ""]
    lines += TESTS.splitlines()
    return "\n".join(lines) + "\n"


def formatted(rust: str) -> str:
    """rustfmt the rendered source so the committed file passes `cargo fmt --check`."""
    import subprocess
    run = subprocess.run(["rustfmt", "--edition", "2024", "--config-path", str(ROOT / "rustfmt.toml"), "--emit", "stdout"],
                         input=rust, text=True, capture_output=True, check=True)
    return run.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--capture", type=Path, default=FIXTURE)
    parser.add_argument("--fixture-out", type=Path)
    parser.add_argument("--rust-out", type=Path, default=RUST)
    args = parser.parse_args()
    capture = json.loads(args.capture.read_text())
    rust = render(capture)
    if args.fixture_out:
        args.fixture_out.write_text(json.dumps(capture, sort_keys=True, indent=1, ensure_ascii=False) + "\n")
    args.rust_out.write_text(formatted(rust))
    print(f"{len(read_lookup(capture))} read-lookup URIs, {len(capture['tables'])} table namespaces, "
          f"{len(capture['std_xlat'])} prefix translations")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
