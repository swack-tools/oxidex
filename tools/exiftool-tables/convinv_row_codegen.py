"""Emit inactive static ConvInv rows from native ``native_write_tables`` facts."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from convinv_rows import Property, Row, compile_rows
from scalar_helper_codegen import rust_string


def _property(value: Property) -> str:
    if value.kind == "Undefined":
        rendered = "PropertyValue::Undefined"
    elif value.kind == "Text":
        rendered = "PropertyValue::Text(" + rust_string(str(value.value)) + ")"
    elif value.kind == "Integer":
        rendered = "PropertyValue::Integer(" + str(value.value) + ")"
    else:
        raise ValueError("unknown projected property kind: " + value.kind)
    return "Property { name: " + rust_string(value.name) + ", value: " + rendered + " }"


def _slice(index: int, label: str, values: tuple[Property, ...]) -> str:
    return "const ROW_%d_%s: &[Property<'static>] = &[%s];\n" % (
        index, label, ", ".join(_property(value) for value in values))


def _row(index: int, row: Row) -> str:
    conversion = ", ".join("ConversionProperty::" + value for value in row.conversion)
    gates = ", ".join("true" if value else "false" for value in row.gates)
    identity = tuple(map(rust_string, (row.module, row.table, row.full_name, row.raw_id, row.name, row.write_group)))
    return """StaticConvInvRow {
    module: %s,
    table: %s,
    full_name: %s,
    raw_id: %s,
    name: %s,
    write_group: %s,
    conversion: [%s],
    gates: [%s],
    tag_properties: ROW_%d_TAG_PROPERTIES,
    table_properties: ROW_%d_TABLE_PROPERTIES,
    tag_groups: ROW_%d_TAG_GROUPS,
}""" % (identity + (conversion, gates, index, index, index))


def generate(document: dict[str, Any]) -> tuple[str, dict[str, Any]]:
    rows, report = compile_rows(document)
    report["exiftool_version"] = document.get("exiftool_version")
    chunks = [
        "// @generated by tools/exiftool-tables/convinv_row_codegen.py.\n",
        "// Inactive source-derived rows; no public tag or writer admission.\n",
        "#![allow(dead_code, unused_imports)]\n",
        "use crate::writers::generated_checkexif::{Property, PropertyValue};\n",
        "use crate::writers::generated_convinv::{ConversionProperty, StaticConvInvRow};\n",
    ]
    for index, row in enumerate(rows):
        chunks.extend((_slice(index, "TAG_PROPERTIES", row.tag_properties),
                       _slice(index, "TABLE_PROPERTIES", row.table_properties),
                       _slice(index, "TAG_GROUPS", row.tag_groups)))
    chunks.append("pub(crate) const CONV_INV_ROWS: &[StaticConvInvRow] = &[\n")
    chunks.extend(_row(index, row) + ",\n" for index, row in enumerate(rows))
    chunks.append("];\n")
    return "".join(chunks), report


def main() -> None:
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tables", type=Path)
    parser.add_argument("-o", "--output", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    source, report = generate(json.loads(args.tables.read_text(encoding="utf-8")))
    args.output.write_text(source, encoding="utf-8")
    args.report.write_text(json.dumps(report, sort_keys=True, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
