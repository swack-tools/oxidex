#!/usr/bin/env python3
"""Generate declarative QuickTime `Keys` specs for the indexed `keys`/`ilst` route.

Only direct Keys-table matches after ProcessKeys' namespace normalization are
emitted. ItemList/UserData fallback and dynamic unknown-name construction remain
explicitly outside this generated reader.
"""
from __future__ import annotations
import argparse, hashlib, json
from pathlib import Path
import quicktime_atom_tables as selector
from quicktime_generated_specs import source_format, rust_string, render_format, processor_reason, reader_protocol_reason

ROOT = selector.ROOT
SNAPSHOT = ROOT / "tools/exiftool-tables/fixtures/quicktime_source_13_59.json"
LEDGER = ROOT / "tools/exiftool-tables/quicktime_generated_keys_ledger.json"
RUST = ROOT / "src/parsers/quicktime/generated_keys_specs.rs"
PROCESSOR = "Image::ExifTool::QuickTime::ProcessKeys"
PROCESSOR_SHA256 = "294ea57533595f3e988c8042e2588f0fa874e46bd456af55936633273f051c76"


def compile_document(document):
    if document.get("exiftool_version") != (ROOT / ".exiftool-version").read_text().strip():
        raise ValueError("fresh source dump differs from repository pin")
    if "hydrated_layouts" in document:
        from capture_quicktime_baseline import hydrated_tables
        tables = hydrated_tables(document)
        module = {**document["modules"]["QuickTime"], "tables": tables, "table_count": len(tables)}
        document = {**document, "modules": {**document["modules"], "QuickTime": module}}
    base = selector.inventory(document)
    table = document["modules"]["QuickTime"]["tables"]["Keys"]
    meta = table["meta"]
    proc = meta.get("PROCESS_PROC", {})
    blocked = processor_reason(document) or reader_protocol_reason(document)
    if blocked is None and (not isinstance(proc, dict) or proc.get("__name") != PROCESSOR or proc.get("__perl") != "CODE" or proc.get("__opaque") is not True):
        blocked = "missing_or_changed_processor_contract:PROCESS_PROC"
    elif blocked is None and hashlib.sha256(proc.get("__deparse", "").encode()).hexdigest() != PROCESSOR_SHA256:
        blocked = "missing_or_changed_processor_contract:PROCESS_PROC"
    elif blocked is None and (meta.get("GROUPS", {}).get("0", "QuickTime") != "QuickTime" or meta.get("GROUPS", {}).get("1") != "Keys" or meta.get("VARS", {}).get("LONG_TAGS") != "9"):
        blocked = "missing_or_changed_processor_contract:Keys_metadata"
    specs=[]; ledger=[]
    keys_family = next(f for f in base["families"] if f["table"] == "Keys")
    for record in keys_family["records"]:
        reasons=[r for r in record["reasons"] if r != "protocol_keys_indexed_name_resolution"]
        if blocked: reasons.append(blocked)
        reasons=sorted(set(reasons))
        generated=not reasons
        entry={"identity":record["identity"],"generated":generated,"reasons":reasons}
        if generated:
            row = record.get("refused_source", record.get("spec", {}))
            pc = row.get("PrintConv")
            enum = pc["map"] if isinstance(pc, dict) else {}
            operand={"source_key":record["identity"]["raw_key"],"name":row["Name"],"group":"Keys","group0":row.get("Groups", {}).get("0", meta["GROUPS"].get("0", "QuickTime")),"source_format":source_format(row.get("Format")),"safe_enum_operands":[{"raw":a,"rendered":b} for a,b in sorted(enum.items())],"source_identity":record["identity"]}
            specs.append(operand); entry["generated_spec_sha256"]=hashlib.sha256(json.dumps(operand,sort_keys=True,separators=(",",":"),ensure_ascii=False).encode()).hexdigest()
        ledger.append(entry)
    specs.sort(key=lambda x:x["source_key"]); ledger.sort(key=lambda x:(x["identity"]["raw_key"],x["identity"]["variant_path"]))
    return {"schema":"quicktime_generated_keys_specs_v1","scope":"direct Keys-table matches in QuickTime meta keys+ilst only; ItemList/UserData fallback and dynamic unknown names are omitted","source":{"exiftool_version":base["exiftool_version"],"table_sha256":keys_family["source_table_sha256"]},"protocol":{"processor":{"__name":PROCESSOR,"__deparse_sha256":PROCESSOR_SHA256,"source_file":proc.get("source_file"),"source_sha256":proc.get("source_sha256")},"normalization":"ProcessKeys: NUL-truncate; for mdta try com./com.apple.quicktime.-stripped key then full key; ordinal starts at 1","eligible":blocked is None,"reason":blocked},"specs":specs,"ledger":ledger,"identity_counts":{"source_records":len(ledger),"generated":len(specs),"omitted":len(ledger)-len(specs)}}

def render_rust(result):
    lines=["// @generated by tools/exiftool-tables/quicktime_keys_specs.py; DO NOT EDIT.","use super::generated_itemlist_specs::{EnumOperand, ItemListSpec, SourceFormat};","","#[derive(Clone, Copy, Debug, Eq, PartialEq)]","pub(crate) struct KeySpec {", "    pub source_key: &'static str,", "    pub data: ItemListSpec,", "}","","#[rustfmt::skip]","pub(crate) static KEYS_SPECS: &[KeySpec] = &["]
    for x in result['specs']:
        es=', '.join('EnumOperand { raw: %s, rendered: %s }'%(rust_string(e['raw']),rust_string(e['rendered'])) for e in x['safe_enum_operands'])
        lines.append('    KeySpec { source_key: %s, data: ItemListSpec { raw_fourcc: [0, 0, 0, 0], name: %s, group: %s, group0: %s, source_format: %s, safe_enum_operands: &[%s] } },'%(rust_string(x['source_key']),rust_string(x['name']),rust_string(x['group']),rust_string(x['group0']),render_format(x['source_format']),es))
    refused = [x["identity"]["raw_key"] for x in result["ledger"] if not x["generated"]]
    lines.extend(['];', '#[rustfmt::skip]', 'pub(crate) static REFUSED_SOURCE_KEYS: &[&str] = &['])
    lines.extend('    ' + rust_string(x) + ',' for x in refused)
    lines.extend(['];', ''])
    return '\n'.join(lines)
def serialized(x): return json.dumps(x,sort_keys=True,indent=2,ensure_ascii=False)+'\n'
def main():
 p=argparse.ArgumentParser();p.add_argument('--dump',type=Path,default=SNAPSHOT);p.add_argument('--ledger',type=Path,default=LEDGER);p.add_argument('--rust',type=Path,default=RUST);p.add_argument('--replace',action='store_true');p.add_argument('--check',action='store_true');a=p.parse_args()
 if a.check and a.replace:p.error('mutually exclusive')
 r=compile_document(json.loads(a.dump.read_text())); outs=[(a.ledger,serialized(r)),(a.rust,render_rust(r))]
 for path,body in outs:
  if a.check:
   if not path.is_file() or path.read_text()!=body:p.error('stale generated Keys artifact: '+str(path))
  else:
   if path.exists() and not a.replace:p.error('output exists: '+str(path))
   path.write_text(body)
if __name__=='__main__':main()
