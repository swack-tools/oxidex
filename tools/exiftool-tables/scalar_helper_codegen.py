"""Generate Rust scalar helper operands from captured native executable rules.

This joins the source compilers to the shared Rust executor. It does not claim
that a tag, its input conversions, encoding or carrier route is admitted.
"""
from dataclasses import asdict
import json
from pathlib import Path
from typing import Any

from checkexif_recipes import RecipeMalformed, RecipeRefused
from checkvalue_recipes import compile_scalar_check
from writevalue_recipes import compile_scalar_write

COMPARISONS = {'<': 'Lt', '<=': 'Le', '==': 'Eq', '!=': 'Ne', '>=': 'Ge', '>': 'Gt'}


def rust_string(value: str) -> str:
    """Escape Rust literals, including control characters JSON spells differently."""
    chunks = ['"']
    for char in value:
        if char in ('"', '\\'):
            chunks.append('\\' + char)
        elif ord(char) < 32 or ord(char) == 127:
            chunks.append('\\u{' + format(ord(char), 'x') + '}')
        else:
            chunks.append(char)
    return ''.join(chunks) + '"'


def _bound(value: int) -> str:
    if type(value) is not int or not -(1 << 63) <= value < (1 << 63):
        raise RecipeRefused('source count bound is outside the Rust i64 operand')
    return str(value)


def _comparison(value: str) -> str:
    if value not in COMPARISONS:
        raise RecipeRefused('source comparison has no Rust operation')
    return 'Comparison::' + COMPARISONS[value]


def _byte(value: str) -> str:
    # Both closed source parsers currently admit only the native NUL literal.
    if value != '\0':
        raise RecipeRefused('source scalar terminator/padding is not admitted')
    return '0'


def _check_fields(recipe) -> dict[str, str]:
    return {
        'formats': '[' + ', '.join(map(rust_string, recipe.formats)) + ']',
        'positive_count_operator': _comparison(recipe.positive_count_operator),
        'positive_count_bound': _bound(recipe.positive_count_bound),
        'first_format': rust_string(recipe.first_format),
        'first_limit_operator': _comparison(recipe.first_limit_operator),
        'first_error': rust_string(recipe.first_error),
        'second_limit_operator': _comparison(recipe.second_limit_operator),
        'second_error': rust_string(recipe.second_error),
        'padding_operator': _comparison(recipe.padding_operator),
        'padding_character': _byte(recipe.padding_character),
    }


def _write_fields(recipe) -> dict[str, str]:
    return {
        'formats': '[' + ', '.join(map(rust_string, recipe.formats)) + ']',
        'terminated_format': rust_string(recipe.terminated_format),
        'count_positive_operator': _comparison(recipe.count_positive_operator),
        'count_positive_bound': _bound(recipe.count_positive_bound),
        'diff_negative_operator': _comparison(recipe.diff_negative_operator),
        'terminator': _byte(recipe.terminator),
    }


def generate(document: dict[str, Any]) -> tuple[str, dict[str, Any]]:
    helpers = document.get('native_write_helpers')
    if not isinstance(helpers, dict):
        raise RecipeMalformed('native_write_helpers is not an object')
    chunks = [
        '// @generated by tools/exiftool-tables/scalar_helper_codegen.py.\n'
        '// Source-derived helper operands; no public tag or writer admission.\n'
        '#![allow(dead_code, unused_imports)]\n'
        'use crate::writers::generated_scalar::{Comparison, ScalarCheckRecipe, ScalarWriteRecipe, NumericScalarRecipe};\n'
    ]
    report = {'scope': 'generated Rust scalar helpers; no tag/carrier/encoding admission',
              'helpers': {}}
    for key, symbol, typ, compiler, fields in (
        ('check_value', 'CHECK_VALUE', 'ScalarCheckRecipe', compile_scalar_check, _check_fields),
        ('write_value', 'WRITE_VALUE', 'ScalarWriteRecipe', compile_scalar_write, _write_fields),
    ):
        try:
            recipe = compiler(helpers.get(key))
            operands = fields(recipe)
        except RecipeRefused as exc:
            chunks.append(f'pub(crate) const {symbol}: Option<{typ}> = None;\n')
            report['helpers'][key] = {'state': 'unsupported', 'reason': str(exc)}
            continue
        provenance = asdict(recipe.provenance)
        report['helpers'][key] = {'state': 'compiled', 'recipe': asdict(recipe)}
        chunks.append(f'pub(crate) const {symbol}: Option<{typ}> = Some({typ} {{\n')
        chunks.extend(f'    {name}: {value},\n' for name, value in operands.items())
        chunks.append('});\n')
        chunks.append(f'pub(crate) const {symbol}_PROVENANCE: &str = '
                      + rust_string(json.dumps(provenance, sort_keys=True)) + ';\n')
    from numeric_scalar import compile_numeric_scalar, render_numeric
    try:
        numeric = compile_numeric_scalar(document)
        report['helpers']['numeric_scalar'] = {'state': 'compiled', 'recipe': asdict(numeric)}
    except RecipeRefused as exc:
        numeric = None
        report['helpers']['numeric_scalar'] = {'state': 'unsupported', 'reason': str(exc)}
    chunks.append(render_numeric(numeric))
    from setnewvalue_addressing import compile_addressing
    from setnewvalue_address_rust_codegen import _source_capture_identity
    try:
        addressing, _ = compile_addressing(document)
        identity = _source_capture_identity(document, addressing)
        directories = addressing.explicit_directories
        report['helpers']['explicit_directories'] = {
            'state': 'compiled', 'directories': directories,
            'source_capture_identity': identity,
            'set_new_value_body_sha256': addressing.set_new_value_body_sha256,
            'undefined_value_bypasses_conversion': True,
        }
        fields = ', '.join(name + ': ' + rust_string(value) for name, value in identity.items())
        chunks.append('pub(crate) const PUBLIC_SET_NEW_VALUE_CALLER: Option<crate::writers::generated_scalar::PublicSetNewValueCallerRecipe> = Some(crate::writers::generated_scalar::PublicSetNewValueCallerRecipe { directories: &[' + ', '.join(map(rust_string, directories)) + '], undefined_value_bypasses_conversion: true, capture: crate::writers::generated_scalar::NativeSourceCapture { ' + fields + ' } });\n')
    except (RecipeRefused, RecipeMalformed) as exc:
        report['helpers']['explicit_directories'] = {'state': 'unsupported', 'reason': str(exc)}
        chunks.append('pub(crate) const PUBLIC_SET_NEW_VALUE_CALLER: Option<crate::writers::generated_scalar::PublicSetNewValueCallerRecipe> = None;\n')
    return '\n'.join(chunks), report


def main() -> None:
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('tables', type=Path)
    parser.add_argument('-o', '--output', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    source, report = generate(json.loads(args.tables.read_text()))
    args.output.write_text(source)
    args.report.write_text(json.dumps(report, sort_keys=True, indent=2) + '\n')


if __name__ == '__main__':
    main()
