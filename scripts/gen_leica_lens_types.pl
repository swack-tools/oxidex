#!/usr/bin/env perl
# Emit Rust source for ExifTool's %Image::ExifTool::Panasonic::leicaLensTypes,
# the PrintConv shared by every Leica LensType tag (Leica2 0x0310, Subdir
# 0x3405 and Data1 0x0016), straight from ExifTool's own in-memory Perl hash
# so the Rust copy cannot drift from the Perl one through transcription.
#
# Every emitted name is additionally traced back to a literal `key => 'name',`
# line in Panasonic.pm before it is written out, and the script dies on any
# construct it has not seen rather than dropping it silently:
#
#   * a value that is a reference rather than a plain scalar
#   * a key that is neither `N` nor `N M` (ExifTool splits the stored int32u
#     into those two integers with `($val >> 2) . " " . ($val & 0x3)`)
#   * either half of a pair outside the range the reader can produce
#     (`N` <= 0xffff because Data1 masks with `& 0xffff`; `M` in 0..3)
#   * a name for which no source line can be found
#
# Usage: perl scripts/gen_leica_lens_types.pl [path/to/Image/ExifTool]
use strict;
use warnings;

my $LIB = $ARGV[0]
    || (-d '/tmp/oxidex-exiftool-cache/exiftool/lib'
        ? '/tmp/oxidex-exiftool-cache/exiftool/lib'
        : '/opt/homebrew/Cellar/exiftool/13.55/libexec/lib/perl5');
eval "use lib '$LIB'; use Image::ExifTool::Panasonic; 1" or die $@;

my $PM = "$LIB/Image/ExifTool/Panasonic.pm";
open(my $fh, '<', $PM) or die "cannot read $PM: $!";
my @src = <$fh>;
close $fh;

sub esc {
    my $s = shift;
    $s =~ s/\\/\\\\/g;
    $s =~ s/"/\\"/g;
    return $s;
}

# Find the literal `key => 'name',` line that defines this entry, so a name
# that is not actually written in Panasonic.pm cannot be emitted.
sub source_line {
    my ($key, $name) = @_;
    my $qk = quotemeta $key;
    my $qn = quotemeta $name;
    for my $i (0 .. $#src) {
        # bare integer keys are written unquoted, "N M" keys are quoted
        next unless $src[$i] =~ /^\s*(?:'$qk'|"$qk"|$qk)\s*=>\s*(?:'$qn'|"$qn")\s*,/;
        return $i + 1;
    }
    return undef;
}

my $h = \%Image::ExifTool::Panasonic::leicaLensTypes;
my (@out, $n_pair, $n_bare);
for my $key (sort keys %$h) {
    next if $key eq 'OTHER' or $key eq 'Notes';
    my $val = $h->{$key};
    die "unhandled: key '$key' holds a " . ref($val) . " reference\n" if ref $val;

    my ($id, $sub);
    if ($key =~ /^(\d+)$/) {
        ($id, $sub) = ($1, undef);
        $n_bare++;
    } elsif ($key =~ /^(\d+) (\d+)$/) {
        ($id, $sub) = ($1, $2);
        $n_pair++;
    } else {
        die "unhandled key shape: '$key'\n";
    }
    die "id $id out of int16u range (key '$key')\n" if $id > 0xffff;
    die "sub-id $sub outside 0..3 (key '$key')\n" if defined $sub and $sub > 3;

    my $line = source_line($key, $val);
    die "no `$key => '$val',` line in Panasonic.pm\n" unless defined $line;

    push @out, [$id, $sub, $val, $line];
}

@out = sort { $a->[0] <=> $b->[0]
              || (defined $a->[1] ? $a->[1] : -1) <=> (defined $b->[1] ? $b->[1] : -1) } @out;

printf STDERR "leicaLensTypes: %d entries (%d bare id, %d 'id sub' pairs)\n",
    scalar(@out), $n_bare, $n_pair;

print <<"HDR";
// GENERATED by scripts/gen_leica_lens_types.pl from ExifTool's
// %Image::ExifTool::Panasonic::leicaLensTypes. Do not edit by hand.

    pub static LEICA_LENS_TYPES: [(u16, Option<u8>, &str); ${\ scalar @out }] = [
HDR
for my $e (@out) {
    my ($id, $sub, $name, $line) = @$e;
    printf("        (%d, %s, \"%s\"), // Panasonic.pm:%d\n",
        $id, defined $sub ? "Some($sub)" : 'None', esc($name), $line);
}
print "    ];\n";
